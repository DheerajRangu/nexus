const dictionaries: Record<Lang, Translation> = { en, te, hi };

export function translate(lang: Lang, key: keyof Translation, vars?: Record<string, string | number>): string {
  let text: string = dictionaries[lang][key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function readLang(): Lang {
  const stored = localStorage.getItem("aegis.citizen.lang");
  if (stored === "te" || stored === "hi" || stored === "en") return stored;
  const browser = navigator.language.toLowerCase();
  if (browser.startsWith("te")) return "te";
  if (browser.startsWith("hi")) return "hi";
  return "en";
}

export function explanationText(lang: Lang, explanationKey: string, fallback: string | null): string | null {
  const key = `explanation.${explanationKey}` as keyof Translation;
  if (key in dictionaries.en) return translate(lang, key);
  return fallback;
}
